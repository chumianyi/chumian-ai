  Future<void> init() async {
    if (_initialized) return;
    _initialized = true;
    _lastUpdated = DateTime.now();
    notifyListeners();
  }

  Future<void> dispose() async {
    _initialized = false;
    notifyListeners();
  }

  void _setLoading(bool loading) {
    _isLoading = loading;
    notifyListeners();
  }

  void _setError(String? error) {
    _lastError = error;
    notifyListeners();
  }

  void _touch() {
    _lastUpdated = DateTime.now();
    notifyListeners();
  }

